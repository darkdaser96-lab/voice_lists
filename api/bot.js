function sbHeaders(extra) {
  const key = supabaseKey();
  return Object.assign(
    {
      apikey: key,
      Authorization: "Bearer " + key,
      "Content-Type": "application/json",
      Prefer: "return=representation",
    },
    extra || {}
  );
}

async function sbRest(pathAndQuery, opts) {
  const base = supabaseUrl();
  if (!base || !supabaseKey()) {
    const err = new Error("no_supabase");
    throw err;
  }
  const method = (opts && opts.method) || "GET";
  const headers = sbHeaders(opts && opts.headers);
  const init = { method, headers };
  if (opts && opts.body != null) {
    init.body =
      typeof opts.body === "string" ? opts.body : JSON.stringify(opts.body);
  }
  const res = await fetch(base + pathAndQuery, init);
  const text = await res.text().catch(() => "");
  let data = null;
  if (text) {
    try {
      data = JSON.parse(text);
    } catch (_) {
      data = text;
    }
  }
  if (!res.ok) {
    const detail =
      (data && data.message) ||
      (data && data.error_description) ||
      (typeof data === "string" ? data.slice(0, 200) : "") ||
      "HTTP " + res.status;
    const err = new Error("supabase_" + res.status + ": " + detail);
    err.status = res.status;
    err.body = data;
    throw err;
  }
  return data;
}

async function tryRunSql(sql) {
  const base = supabaseUrl();
  const key = supabaseKey();
  if (!base || !key) return false;
  const attempts = [
    { path: "/pg/query", body: { query: sql } },
    { path: "/pg-meta/default/query", body: { query: sql } },
    { path: "/rest/v1/rpc/exec_sql", body: { query: sql } },
    { path: "/rest/v1/rpc/sql", body: { query: sql } },
  ];
  for (const a of attempts) {
    try {
      const res = await fetch(base + a.path, {
        method: "POST",
        headers: sbHeaders(),
        body: JSON.stringify(a.body),
      });
      if (res.ok) {
        await res.text().catch(() => "");
        return true;
      }
      await res.text().catch(() => "");
    } catch (_) {}
  }
  return false;
}

async function ensureSchema() {
  if (schemaAttempted) return schemaOk;
  schemaAttempted = true;
  if (!supabaseConfigured()) {
    schemaOk = false;
    return false;
  }
  schemaOk = await tryRunSql(SCHEMA_SQL);
  return schemaOk;
}

function getEph(chatId) {
  const key = String(chatId);
  if (!ephemeral.has(key)) {
    ephemeral.set(key, {
      step: null,
      pendingDeletes: null,
      warnedEphemeral: false,
    });
  }
  return ephemeral.get(key);
}

function syncEph(state) {
  const e = state._eph;
  e.step = state.step;
  e.pendingDeletes = state.pendingDeletes;
  e.warnedEphemeral = state.warnedEphemeral;
}

async function loadChat(chatId) {
  await ensureSchema();
  if (!supabaseConfigured()) {
    throw new Error("no_supabase");
  }
  const key = String(chatId);
  const eph = getEph(key);

  let listRows;
  let noteRows;
  try {
    listRows = await sbRest(
      "/rest/v1/lists?chat_id=eq." +
        encodeURIComponent(key) +
        "&select=*&order=sort_order.asc"
    );
    noteRows = await sbRest(
      "/rest/v1/notes?chat_id=eq." +
        encodeURIComponent(key) +
        "&select=id,list_name,body&order=id.asc"
    );
  } catch (err) {
    throw err;
  }
  if (!Array.isArray(listRows)) listRows = [];
  if (!Array.isArray(noteRows)) noteRows = [];

  const state = {
    chatId: key,
    lists: {},
    noteIds: {},
    order: [],
    starred: [],
    step: eph.step,
    pendingDeletes: eph.pendingDeletes,
    warnedEphemeral: eph.warnedEphemeral,
    _eph: eph,
  };

  for (const row of listRows) {
    const name = row.name;
    if (!name) continue;
    state.lists[name] = [];
    state.noteIds[name] = [];
    state.order.push(name);
    if (row.starred) state.starred.push(name);
  }

  for (const row of noteRows) {
    const ln = row.list_name;
    if (!ln) continue;
    if (!Array.isArray(state.lists[ln])) {
      state.lists[ln] = [];
      state.noteIds[ln] = [];
      if (!state.order.includes(ln)) state.order.push(ln);
    }
    state.lists[ln].push(row.body);
    state.noteIds[ln].push(row.id);
  }

  await migrateIncomingToStickersDb(state);
  await ensureDefaultListDb(state);
  return state;
}

async function ensureDefaultListDb(state) {
  if (!Array.isArray(state.lists[DEFAULT_LIST])) {
    state.lists[DEFAULT_LIST] = [];
    state.noteIds[DEFAULT_LIST] = [];
  }
  if (!state.order.includes(DEFAULT_LIST)) {
    state.order.unshift(DEFAULT_LIST);
  }
  const exists = await sbRest(
    "/rest/v1/lists?chat_id=eq." +
      encodeURIComponent(state.chatId) +
      "&name=eq." +
      encodeURIComponent(DEFAULT_LIST) +
      "&select=name"
  );
  if (!Array.isArray(exists) || !exists.length) {
    await sbRest("/rest/v1/lists", {
      method: "POST",
      headers: sbHeaders({
        Prefer: "return=representation,resolution=merge-duplicates",
      }),
      body: {
        chat_id: state.chatId,
        name: DEFAULT_LIST,
        starred: false,
        sort_order: 0,
      },
    });
  }
}

async function migrateIncomingToStickersDb(state) {
  if (!Object.prototype.hasOwnProperty.call(state.lists, LEGACY_DEFAULT)) {
    return;
  }
  const legacyNotes = state.lists[LEGACY_DEFAULT] || [];
  const legacyIds = state.noteIds[LEGACY_DEFAULT] || [];
  const legacyStarred = (state.starred || []).includes(LEGACY_DEFAULT);

  if (!Array.isArray(state.lists[DEFAULT_LIST])) {
    state.lists[DEFAULT_LIST] = [];
    state.noteIds[DEFAULT_LIST] = [];
  }

  // Move notes in DB
  if (legacyIds.length) {
    await sbRest(
      "/rest/v1/notes?chat_id=eq." +
        encodeURIComponent(state.chatId) +
        "&list_name=eq." +
        encodeURIComponent(LEGACY_DEFAULT),
      {
        method: "PATCH",
        body: { list_name: DEFAULT_LIST },
      }
    );
  }

  state.lists[DEFAULT_LIST] = state.lists[DEFAULT_LIST].concat(legacyNotes);
  state.noteIds[DEFAULT_LIST] = state.noteIds[DEFAULT_LIST].concat(legacyIds);
  delete state.lists[LEGACY_DEFAULT];
  delete state.noteIds[LEGACY_DEFAULT];

  // Ensure Стикеры list row, merge starred, drop legacy row
  const stickersExists = await sbRest(
    "/rest/v1/lists?chat_id=eq." +
      encodeURIComponent(state.chatId) +
      "&name=eq." +
      encodeURIComponent(DEFAULT_LIST) +
      "&select=name,starred,sort_order"
  );
  if (!Array.isArray(stickersExists) || !stickersExists.length) {
    await sbRest("/rest/v1/lists", {
      method: "POST",
      body: {
        chat_id: state.chatId,
        name: DEFAULT_LIST,
        starred: legacyStarred,
        sort_order: 0,
      },
    });
  } else if (legacyStarred && !stickersExists[0].starred) {
    await sbRest(
      "/rest/v1/lists?chat_id=eq." +
        encodeURIComponent(state.chatId) +
        "&name=eq." +
        encodeURIComponent(DEFAULT_LIST),
      { method: "PATCH", body: { starred: true } }
    );
  }

  await sbRest(
    "/rest/v1/lists?chat_id=eq." +
      encodeURIComponent(state.chatId) +
      "&name=eq." +
      encodeURIComponent(LEGACY_DEFAULT),
    { method: "DELETE", headers: sbHeaders({ Prefer: "return=minimal" }) }
  );

  state.order = (state.order || [])
    .map((n) => (n === LEGACY_DEFAULT ? DEFAULT_LIST : n))
    .filter((n, i, arr) => n && arr.indexOf(n) === i);
  if (!state.order.includes(DEFAULT_LIST)) state.order.unshift(DEFAULT_LIST);
  state.starred = (state.starred || [])
    .map((n) => (n === LEGACY_DEFAULT ? DEFAULT_LIST : n))
    .filter((n, i, arr) => n && arr.indexOf(n) === i && state.lists[n]);
}

