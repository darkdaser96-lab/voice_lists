async function dbRenameList(state, oldName, newName) {
  const conflict = await sbRest(
    "/rest/v1/lists?chat_id=eq." +
      encodeURIComponent(state.chatId) +
      "&name=eq." +
      encodeURIComponent(newName) +
      "&select=name"
  );
  if (Array.isArray(conflict) && conflict.length) {
    const err = new Error("name_taken");
    throw err;
  }
  // Update notes first, then list PK via delete+insert or patch name
  await sbRest(
    "/rest/v1/notes?chat_id=eq." +
      encodeURIComponent(state.chatId) +
      "&list_name=eq." +
      encodeURIComponent(oldName),
    { method: "PATCH", body: { list_name: newName } }
  );
  const oldRows = await sbRest(
    "/rest/v1/lists?chat_id=eq." +
      encodeURIComponent(state.chatId) +
      "&name=eq." +
      encodeURIComponent(oldName) +
      "&select=*"
  );
  const old = Array.isArray(oldRows) && oldRows[0] ? oldRows[0] : null;
  await sbRest("/rest/v1/lists", {
    method: "POST",
    headers: sbHeaders({
      Prefer: "return=representation,resolution=merge-duplicates",
    }),
    body: {
      chat_id: state.chatId,
      name: newName,
      starred: old ? Boolean(old.starred) : false,
      sort_order: old ? old.sort_order : 0,
    },
  });
  await sbRest(
    "/rest/v1/lists?chat_id=eq." +
      encodeURIComponent(state.chatId) +
      "&name=eq." +
      encodeURIComponent(oldName),
    { method: "DELETE", headers: sbHeaders({ Prefer: "return=minimal" }) }
  );
}

async function tg(method, body) {
  const t = token();
  if (!t) throw new Error("TELEGRAM_BOT_TOKEN is not set");
  const res = await fetch(`https://api.telegram.org/bot${t}/${method}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok || data.ok === false) {
    const msg =
      (data && data.description) || `Telegram ${method} HTTP ${res.status}`;
    throw new Error(msg);
  }
  return data;
}

async function tgGet(method, query) {
  const t = token();
  if (!t) throw new Error("TELEGRAM_BOT_TOKEN is not set");
  const qs = new URLSearchParams(query || {}).toString();
  const url =
    `https://api.telegram.org/bot${t}/${method}` + (qs ? "?" + qs : "");
  const res = await fetch(url);
  const data = await res.json().catch(() => ({}));
  if (!res.ok || data.ok === false) {
    const msg =
      (data && data.description) || `Telegram ${method} HTTP ${res.status}`;
    throw new Error(msg);
  }
  return data;
}

